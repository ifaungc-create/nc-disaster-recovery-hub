// Collects every t('…') / t("…") / tk('…') key in src/ and writes src/i18n/en.js (English = the key).
// Run: node scripts/i18n-extract.mjs   (tests/i18n.test.mjs checks en.js is current and es.js is complete)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
const ROOT = new URL('..', import.meta.url).pathname;
const files = []; const walk = (d) => readdirSync(d).forEach((f) => { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (/\.js$/.test(f) && !/i18n\/(en|es)\.js$/.test(p)) files.push(p); });
walk(join(ROOT, 'src'));
const RE = /\bt[k]?\((['"])((?:\\.|(?!\1)[^\\])*)\1/g;
const unesc = (s, q) => s.replace(/\\(.)/g, (m, c) => (c === 'n' ? '\n' : c));
export function extract() {
  const keys = new Set();
  for (const f of files) { const src = readFileSync(f, 'utf8'); for (const m of src.matchAll(RE)) keys.add(unesc(m[2], m[1])); }
  return [...keys].sort();
}
export const render = (keys) => `// GENERATED by scripts/i18n-extract.mjs from the t('…') calls in src/. Do not edit by hand.\n// English text is the key. Spanish translations live in es.js.\nexport default {\n${keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(k)},`).join('\n')}\n};\n`;
if (process.argv[1] && process.argv[1].endsWith('i18n-extract.mjs')) { const k = extract(); writeFileSync(join(ROOT, 'src/i18n/en.js'), render(k)); console.log(`en.js: ${k.length} keys`); }
